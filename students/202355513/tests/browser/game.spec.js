import {test,expect} from '@playwright/test';

test('desktop: start, move, pause, deadline, save, retry, switch modes',async({page})=>{
  test.setTimeout(65000);
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto('/');
  await expect(page.locator('#start')).toBeVisible();
  await page.screenshot({path:'images/homebound-desktop.png',fullPage:true});
  await page.locator('#start').click();
  await expect(page.locator('#welcome')).toBeHidden();
  await page.keyboard.press('ArrowUp');
  await expect(page.locator('#distance')).toContainText('1');
  await page.waitForTimeout(200);
  await page.keyboard.press('ArrowUp');
  await expect(page.locator('#distance')).toContainText('2');
  await page.keyboard.press('p');
  await expect(page.locator('#paused')).toBeVisible();
  await page.locator('#resume').click();
  await expect(page.locator('#paused')).toBeHidden();
  await page.screenshot({path:'images/homebound-playing.png'});
  await expect(page.locator('#result')).toBeVisible({timeout:25000});
  await expect(page.locator('#reason')).toContainText('마감');
  await page.locator('#nickname').fill('브라우저검증');
  await page.locator('#save').click();
  await expect(page.locator('#save-message')).toContainText('저장 완료');
  await expect(page.locator('#rankings')).toContainText('브라우저검증');
  await page.screenshot({path:'images/homebound-result.png'});
  await page.locator('#retry').click();
  await expect(page.locator('#result')).toBeHidden();
  await expect(page.locator('#distance')).toContainText('0');
  await expect(page.locator('#result')).toBeVisible({timeout:25000});
  await page.locator('#back').click();
  await page.locator('#endless').click();
  await expect(page.locator('#endless')).toHaveAttribute('aria-pressed','true');
  expect(errors).toEqual([]);
});

test('mobile touch controls and administrator authentication',async({page})=>{
  await page.setViewportSize({width:390,height:844});
  await page.goto('/');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:'images/homebound-mobile.png',fullPage:true});
  await page.locator('#start').click();
  await expect(page.locator('#welcome')).toBeHidden();
  await page.locator('[data-move=up]').dispatchEvent('pointerdown');
  await expect(page.locator('#distance')).toContainText('1');
  await page.locator('#pause').click();
  await expect(page.locator('#paused')).toBeVisible();
  await page.locator('#exit-focus').click();
  await page.locator('#admin-open').click();
  await page.locator('#admin-password').fill('wrong');
  await page.locator('#admin-confirm').check();
  await page.locator('#admin-form button[type=submit]').click();
  await expect(page.locator('#admin-message')).toContainText('올바르지');
  await page.locator('#admin-password').fill('browser-test-admin');
  await page.locator('#admin-form button[type=submit]').click();
  await expect(page.locator('#admin-message')).toContainText('초기화했습니다');
  await page.locator('#admin-close').click();
  await expect(page.locator('#admin-dialog')).not.toBeVisible();
});
